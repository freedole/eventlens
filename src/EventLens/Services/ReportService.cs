using System.Net;
using System.Text;
using EventLens.Models;
using EventLens.ViewModels;

namespace EventLens.Services;

/// <summary>Self-contained HTML health report (one file, inline CSS) for sending to a manager or client.</summary>
public static class ReportService
{
    public static string Build(DashboardViewModel d, IReadOnlyList<RestartInfo>? restarts)
    {
        string H(string? s) => WebUtility.HtmlEncode(s ?? "");
        string scoreColor = d.Score >= 85 ? "#2e9e57" : d.Score >= 60 ? "#d98c00" : "#d93a3f";

        var sb = new StringBuilder();
        sb.Append($$"""
<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>EventLens report - {{H(d.MachineName)}}</title>
<style>
:root{--bg:#f6f7f9;--card:#fff;--text:#1b1f24;--muted:#5f6b7a;--line:#e3e7ec}
@media (prefers-color-scheme:dark){:root{--bg:#16181c;--card:#1f2228;--text:#eceff3;--muted:#9aa5b1;--line:#2c3038}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--text);font:15px/1.5 "Segoe UI",system-ui,sans-serif}
.wrap{max-width:960px;margin:0 auto;padding:32px 20px}
.card{background:var(--card);border:1px solid var(--line);border-radius:14px;padding:22px;margin-bottom:16px}
.hero{display:flex;gap:28px;align-items:center}
.ring{width:120px;height:120px;border-radius:50%;display:grid;place-items:center;flex:none;
 background:conic-gradient({{scoreColor}} {{d.Score * 3.6:0}}deg,var(--line) 0)}
.ring div{width:96px;height:96px;border-radius:50%;background:var(--card);display:grid;place-items:center;font-size:34px;font-weight:600}
h1{margin:0;font-size:30px;color:{{scoreColor}}}h2{font-size:18px;margin:0 0 12px}
.muted{color:var(--muted)}.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(200px,1fr));gap:12px}
.stat{border:1px solid var(--line);border-radius:10px;padding:12px 14px}.stat b{font-size:26px;display:block}
.Good{border-left:4px solid #2e9e57}.Warn{border-left:4px solid #d98c00}.Bad{border-left:4px solid #d93a3f}.Neutral{border-left:4px solid #3b8ee8}
table{width:100%;border-collapse:collapse}td,th{text-align:left;padding:8px 6px;border-bottom:1px solid var(--line);vertical-align:top;font-size:14px}
th{color:var(--muted);font-weight:600}.foot{font-size:12px;color:var(--muted);text-align:center;margin-top:24px}
</style></head><body><div class="wrap">
<div class="card hero"><div class="ring"><div>{{d.Score}}</div></div>
<div><div class="muted">{{H(d.MachineName)}} · {{DateTime.Now:yyyy-MM-dd HH:mm}}</div><h1>{{H(d.Verdict)}}</h1>
<div>{{H(d.VerdictDetail)}}</div><div class="muted" style="margin-top:8px">Uptime {{H(d.Uptime)}} · booted {{H(d.LastBoot)}}</div></div></div>
<div class="card"><h2>At a glance</h2><div class="grid">
""");
        foreach (var c in d.Cards)
            sb.Append($"<div class=\"stat {c.State}\"><span class=\"muted\">{H(c.Title)}</span><b>{H(c.Value)}</b><span class=\"muted\">{H(c.Hint)}</span></div>");
        sb.Append("</div></div>");

        if (restarts is { Count: > 0 })
        {
            sb.Append("<div class=\"card\"><h2>Recent restarts</h2><table><tr><th>Boot</th><th>Type</th><th>Cause</th><th>Uptime before</th></tr>");
            foreach (var r in restarts.Take(10))
                sb.Append($"<tr><td>{r.BootTime:yyyy-MM-dd HH:mm}</td><td>{H(r.KindText)}</td><td><b>{H(r.Title)}</b><br><span class=\"muted\">{H(r.Detail)}</span></td><td>{H(r.UptimeText)}</td></tr>");
            sb.Append("</table></div>");
        }

        if (d.Timeline.Count > 0)
        {
            sb.Append("<div class=\"card\"><h2>Notable events (30 days)</h2><table><tr><th>Time</th><th>Event</th><th>What to do</th></tr>");
            foreach (var e in d.Timeline)
                sb.Append($"<tr><td>{e.TimeCreated:yyyy-MM-dd HH:mm}</td><td><b>{H(e.Summary)}</b><br><span class=\"muted\">{H(e.Provider)} · ID {e.Id}</span></td><td>{H(e.Explanation?.Action)}</td></tr>");
            sb.Append("</table></div>");
        }

        sb.Append("<div class=\"foot\">Generated by EventLens · github.com/freedole/eventlens</div></div></body></html>");
        return sb.ToString();
    }
}
